	/**
	 * Health probe used by smoke tests.
	 *
	 * @return \WP_REST_Response
	 */
	public static function health() {
		return rest_ensure_response(
			array(
				'ok'       => true,
				'version'  => defined( 'WFO_VERSION' ) ? WFO_VERSION : '0',
				'currency' => (string) Settings::get( 'currency', 'USD' ),
			)
		);
	}

	/**
	 * Validate, re-price and store an order.
	 *
	 * @param \WP_REST_Request $request Request.
	 * @return \WP_REST_Response|\WP_Error
	 */
	public static function create_order( $request ) {
		$params = $request->get_json_params();

		if ( ! is_array( $params ) ) {
			return self::rest_error( 'wfo_invalid', __( 'The order could not be read.', 'whatsapp-menu-orders' ), 400 );
		}

		$result = Order::create( $params );

		if ( ! is_wp_error( $result ) ) {
			self::record_attempt( 'order' );
		}

		if ( is_wp_error( $result ) ) {
			$data   = $result->get_error_data();
			$data   = is_array( $data ) ? $data : array();
			$status = self::status_for( $result->get_error_code(), $data );

			$data['status'] = $status;

			return new \WP_Error( $result->get_error_code(), $result->get_error_message(), $data );
		}

		return rest_ensure_response( $result );
	}

	/**
	 * Content-type, method, throttle, honeypot and timestamp protection.
	 *
	 * Runs before the route's argument validation: every POST is counted in a
	 * loose bucket, while only accepted orders consume the order limit.
	 *
	 * @param mixed            $result  Result from earlier filters.
	 * @param \WP_REST_Server  $server  Server instance.
	 * @param \WP_REST_Request $request Current request.
	 * @return mixed
	 */
	public static function guard_request( $result, $server, $request ) {
		unset( $server );

		if ( ! empty( $result ) || ! $request instanceof \WP_REST_Request ) {
			return $result;
		}

		$route = untrailingslashit( '/' . ltrim( (string) $request->get_route(), '/' ) );

		if ( '/' . self::NAMESPACE_V1 . '/orders' !== $route ) {
			return $result;
		}

		if ( 'POST' !== strtoupper( (string) $request->get_method() ) ) {
			return self::rest_error( 'wfo_invalid', __( 'Only POST requests are accepted.', 'whatsapp-menu-orders' ), 405 );
		}

		$content_type = $request->get_content_type();
		$type         = is_array( $content_type ) && isset( $content_type['value'] ) ? $content_type['value'] : '';

		if ( 'application/json' !== $type ) {
			return self::rest_error( 'wfo_invalid', __( 'Orders must be sent as application/json.', 'whatsapp-menu-orders' ), 415 );
		}

		$throttle = self::check_throttle();

		if ( is_wp_error( $throttle ) ) {
			return $throttle;
		}

		$params = $request->get_json_params();

		if ( ! is_array( $params ) ) {
			// WordPress reports invalid JSON itself with a 400.
			return $result;
		}

		$honeypot = isset( $params['hp'] ) && is_scalar( $params['hp'] ) ? trim( (string) $params['hp'] ) : '';

		if ( '' !== $honeypot ) {
			return self::rest_error( 'wfo_invalid', __( 'The order could not be processed.', 'whatsapp-menu-orders' ), 400 );
		}

		$stamp = isset( $params['t'] ) && is_numeric( $params['t'] ) ? (int) $params['t'] : 0;
		$age   = time() - $stamp;

		if ( $stamp <= 0 || $age < 2 || $age > 24 * HOUR_IN_SECONDS ) {
			return self::rest_error( 'wfo_invalid', __( 'The form expired. Please reload the page and try again.', 'whatsapp-menu-orders' ), 400 );
		}

		return $result;
	}

	/**
	 * Per-IP fixed-window throttle with two buckets.
	 *
	 * `order` counts only orders that were actually accepted, so a customer who
	 * fixes a validation error is never locked out. `hit` is a much looser
	 * bucket on every request, to keep malformed traffic from hammering the
	 * endpoint.
	 *
	 * @return true|\WP_Error
	 */
	private static function check_throttle() {
		/**
		 * Filter the number of accepted orders allowed per window. 0 disables the limit.
		 *
		 * @param int $limit Orders per window.
		 */
		$order_limit = (int) apply_filters( 'wfo_order_throttle_limit', 10 );

		/**
		 * Filter the number of requests (valid or not) allowed per window.
		 *
		 * @param int $limit Requests per window.
		 */
		$hit_limit = (int) apply_filters( 'wfo_request_throttle_limit', 30 );

		/**
		 * Filter the throttle window, in seconds.
		 *
		 * @param int $window Window length.
		 */
		$window = (int) apply_filters( 'wfo_order_throttle_window', 10 * MINUTE_IN_SECONDS );

		if ( $window < 1 ) {
			return true;
		}

		$retry_after = $window - ( time() % $window );

		if ( $order_limit > 0 && self::throttle_count( 'order', $window ) >= $order_limit ) {
			return self::rest_error(
				'wfo_throttled',
				__( 'Too many order attempts. Please wait a few minutes and try again.', 'whatsapp-menu-orders' ),
				429,
				array( 'retry_after' => $retry_after )
			);
		}

		if ( $hit_limit > 0 && self::throttle_count( 'hit', $window ) >= $hit_limit ) {
			return self::rest_error(
				'wfo_throttled',
				__( 'Too many order attempts. Please wait a few minutes and try again.', 'whatsapp-menu-orders' ),
				429,
				array( 'retry_after' => $retry_after )
			);
		}

		// Every request counts against the loose bucket, including invalid ones.
		self::record_attempt( 'hit', $window );

		return true;
	}

	/**
	 * Read a bucket counter without incrementing it.
	 *
	 * @param string $kind   `order` or `hit`.
	 * @param int    $window Window length in seconds.
	 * @return int
	 */
	private static function throttle_count( $kind, $window ) {
		return (int) get_transient( self::throttle_key( $kind, $window ) );
	}

	/**
	 * Increment a bucket counter.
	 *
	 * @param string $kind   `order` or `hit`.
	 * @param int    $window Optional window length in seconds.
	 */
	public static function record_attempt( $kind, $window = 0 ) {
		if ( $window < 1 ) {
			/** This filter is documented in includes/class-rest.php */
			$window = (int) apply_filters( 'wfo_order_throttle_window', 10 * MINUTE_IN_SECONDS );
		}

		$key = self::throttle_key( $kind, $window );

		set_transient( $key, (int) get_transient( $key ) + 1, $window );
	}

	/**
	 * Transient key for a bucket, scoped to the client IP and a fixed window.
	 *
	 * @param string $kind   `order` or `hit`.
	 * @param int    $window Window length in seconds.
	 * @return string
	 */
	private static function throttle_key( $kind, $window ) {
		$ip     = self::client_ip();
		$bucket = (int) floor( time() / $window );

		return 'wfo_thr_' . $kind . '_' . substr( hash( 'sha256', $ip . '|' . wp_salt( 'nonce' ) ), 0, 24 ) . '_' . $bucket;
	}

	/**
	 * Best-effort client IP. Reverse-proxy headers are deliberately ignored.
	 *
	 * @return string
	 */
	private static function client_ip() {
		$ip = isset( $_SERVER['REMOTE_ADDR'] ) ? sanitize_text_field( wp_unslash( $_SERVER['REMOTE_ADDR'] ) ) : '';

		/**
		 * Filter the client IP used for throttling and the order audit hash.
		 *
		 * @param string $ip Detected IP.
		 */
		$ip = (string) apply_filters( 'wfo_client_ip', $ip );

		return '' !== $ip ? $ip : 'unknown';
	}

	/**
	 * Map a WP_Error to an HTTP status, preferring the status Order provided.
	 *
	 * @param string $code Error code.
	 * @param array  $data Error data.
	 * @return int
	 */
	private static function status_for( $code, $data ) {
		if ( isset( $data['status'] ) && in_array( (int) $data['status'], array( 400, 409, 429 ), true ) ) {
			return (int) $data['status'];
		}

		if ( 'wfo_throttled' === $code ) {
			return 429;
		}

		if ( in_array( $code, array( 'wfo_unavailable', 'wfo_min_order', 'wfo_disabled' ), true ) ) {
			return 409;
		}

		return 400;
	}

	/**
	 * Build a REST-friendly WP_Error.
	 *
	 * @param string $code    Machine readable code.
	 * @param string $message Translated message.
	 * @param int    $status  HTTP status.
	 * @param array  $extra   Extra data.
	 * @return \WP_Error
	 */
	private static function rest_error( $code, $message, $status, $extra = array() ) {
		return new \WP_Error( $code, $message, array_merge( array( 'status' => (int) $status ), (array) $extra ) );
	}
}
