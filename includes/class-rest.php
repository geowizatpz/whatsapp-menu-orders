<?php
/**
 * Public REST API for order intake.
 *
 * POST /wp-json/wfo/v1/orders is intentionally nonce-free so page-cached menu
 * pages can still post orders. It is protected by a honeypot, a signed-age
 * timestamp field, a per-IP transient throttle and a strict JSON schema.
 *
 * @package WFO
 */

namespace WFO;

defined( 'ABSPATH' ) || exit;

/**
 * REST route registration and request protection.
 */
class Rest {

	/**
	 * REST namespace.
	 */
	const NAMESPACE_V1 = 'wfo/v1';

	/**
	 * Register hooks.
	 */
	public static function init() {
		add_action( 'rest_api_init', array( __CLASS__, 'register_routes' ) );
		add_filter( 'rest_pre_dispatch', array( __CLASS__, 'guard_request' ), 10, 3 );
	}

	/**
	 * Register the endpoints.
	 */
	public static function register_routes() {
		register_rest_route(
			self::NAMESPACE_V1,
			'/orders',
			array(
				'methods'             => 'POST',
				'callback'            => array( __CLASS__, 'create_order' ),
				'permission_callback' => '__return_true',
				'args'                => self::order_args(),
			)
		);

		register_rest_route(
			self::NAMESPACE_V1,
			'/health',
			array(
				'methods'             => 'GET',
				'callback'            => array( __CLASS__, 'health' ),
				'permission_callback' => '__return_true',
			)
		);
	}

